// NODE_PATH=/path/with/world-atlas+topojson-client node scripts/make-map.cjs
// Builds europe-map.js: Natural Earth countries (via world-atlas, public domain) as simplified SVG paths in a
// Lambert azimuthal equal-area projection. The widget draws them as a dot grid, so the coarse coastline never shows.
const fs = require('fs');
const path = require('path');
const topojson = require('topojson-client');
const topo = JSON.parse(fs.readFileSync(require.resolve('world-atlas/countries-50m.json'), 'utf8'));

const LON0 = 14, LAT0 = 54, rad = Math.PI / 180;
const proj = (lon, lat) => {
  const l = (lon - LON0) * rad, p = lat * rad, p0 = LAT0 * rad;
  const k = Math.sqrt(2 / (1 + Math.sin(p0) * Math.sin(p) + Math.cos(p0) * Math.cos(p) * Math.cos(l)));
  return [k * Math.cos(p) * Math.sin(l), k * (Math.cos(p0) * Math.sin(p) - Math.sin(p0) * Math.cos(p) * Math.cos(l))];
};
// the view: a lon/lat window, fitted to 1000 units wide
const WIN = { lon: [-10, 40], lat: [46.5, 70.5] };
let minx = 1e9, maxx = -1e9, miny = 1e9, maxy = -1e9;
for (let i = 0; i <= 200; i++) for (const [lon, lat] of [[WIN.lon[0] + (i / 200) * (WIN.lon[1] - WIN.lon[0]), WIN.lat[0]], [WIN.lon[0] + (i / 200) * (WIN.lon[1] - WIN.lon[0]), WIN.lat[1]], [WIN.lon[0], WIN.lat[0] + (i / 200) * (WIN.lat[1] - WIN.lat[0])], [WIN.lon[1], WIN.lat[0] + (i / 200) * (WIN.lat[1] - WIN.lat[0])]]) {
  const [x, y] = proj(lon, lat); minx = Math.min(minx, x); maxx = Math.max(maxx, x); miny = Math.min(miny, y); maxy = Math.max(maxy, y);
}
const W = 1000, R = W / (maxx - minx), H = Math.round((maxy - miny) * R);
const scr = (lon, lat) => { const [x, y] = proj(lon, lat); return [(x - minx) * R, (maxy - y) * R]; };
const inView = ([x, y], m = 40) => x > -m && x < W + m && y > -m && y < H + m;

function dp(pts, tol) { // Douglas-Peucker
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length); keep[0] = keep[pts.length - 1] = 1;
  const stack = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop(); let dmax = 0, idx = -1;
    const [ax, ay] = pts[a], [bx, by] = pts[b], dx = bx - ax, dy = by - ay, len = Math.hypot(dx, dy) || 1;
    for (let i = a + 1; i < b; i++) { const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + bx * ay - by * ax) / len; if (d > dmax) { dmax = d; idx = i; } }
    if (dmax > tol) { keep[idx] = 1; stack.push([a, idx], [idx, b]); }
  }
  return pts.filter((_, i) => keep[i]);
}
// a closed ring has identical end points, which breaks the line distance above: simplify its two halves separately
function dpRing(pts, tol) { const m = Math.floor(pts.length / 2); const a = dp(pts.slice(0, m + 1), tol), b = dp(pts.slice(m), tol); return a.concat(b.slice(1)); }
const fmt = (n) => String(Math.round(n * 10) / 10);
const ringPath = (r) => 'M' + r.map(([x, y]) => fmt(x) + ' ' + fmt(y)).join('L') + 'Z';
const linePath = (r) => 'M' + r.map(([x, y]) => fmt(x) + ' ' + fmt(y)).join('L');
const area = (r) => Math.abs(r.reduce((a, [x, y], i) => { const [x2, y2] = r[(i + 1) % r.length]; return a + (x * y2 - x2 * y); }, 0) / 2);

const countries = topojson.feature(topo, topo.objects.countries).features.filter((f) => f.properties.name !== 'Antarctica');
let land = '';
for (const f of countries) {
  const polys = f.geometry.type === 'Polygon' ? [f.geometry.coordinates] : f.geometry.coordinates;
  for (const poly of polys) for (const ring of poly) {
    const pts = ring.map(([lo, la]) => scr(lo, la));
    if (!pts.some((p) => inView(p, 20))) continue;
    const s = dpRing(pts, 0.55);
    if (s.length < 4 || area(s) < 5) continue;
    land += ringPath(s);
  }
}
let borders = '';
const mesh = topojson.mesh(topo, topo.objects.countries, (a, b) => a !== b);
for (const line of mesh.coordinates) {
  const pts = line.map(([lo, la]) => scr(lo, la));
  if (!pts.some((p) => inView(p, 20))) continue;
  const s = dp(pts, 0.55);
  if (s.length >= 2) borders += linePath(s);
}
const out = `// Europe for <founder-tables-outreach>: generated by scripts/make-map.cjs from Natural Earth (public domain) via world-atlas.\nwindow.FT_EUROPE = ${JSON.stringify({ w: W, h: H, lon0: LON0, lat0: LAT0, minx, maxy, R, land, borders })};\n`;
fs.writeFileSync(path.join(__dirname, '..', 'europe-map.js'), out);
console.log('europe-map.js', Math.round(out.length / 1024) + ' KB', 'view', W, 'x', H);
